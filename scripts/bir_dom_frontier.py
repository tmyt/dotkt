"""Temporary direct entry from the remaining owning DOM passes, without IR serde.

Generated from the same source/physical composition as the owning records. This
adapter is deleted with the last DOM pass; it is not a second internal IR or a
transport codec. Source aliases never enter that remaining DOM graph.
"""
import json
from bir_lowering_models import base, compose_shapes, csharp_type, declaration_cases, is_nullable, refkey


def outputs(root, definitions):
    shapes = compose_shapes(definitions)
    cs = lambda field: csharp_type(field, shapes)
    lines = ["// <auto-generated />", "// Source: docs/bir-cir.schema.json; run scripts/generate-ir-model.py.",
             "#nullable enable", "using System.Text.Json.Nodes;", "using DotKt.Cir;",
             "namespace DotKt.Bir.Lowering;", "", "// Removed when the remaining DOM-owning passes are migrated.",
             "internal static class BirGraphDom", "{"]

    def read(field, value="value", nesting=0):
        field = base(field)
        if codec := field.get("x-dotkt-csharp-codec"):
            if field.get("type") == "object": return f"{codec}.Read({value}!)"
            return f"{codec}.ReadFrozenText({value}!.GetValue<string>())"
        if cs(field) == "byte[]": return f"Convert.FromBase64String({value}!.GetValue<string>())"
        if field.get("x-dotkt-kotlin-json-type"):
            return f"TypeNode.Parse({value}!.GetValue<string>())"
        key = refkey(field)
        if key:
            if key == "type": return f"TypeNode.Read({value}) ?? throw new FormatException()"
            if key == "literalValue": return f"BirLiteral.Read({value})"
            if key == "birSourceTypeAlias": return "throw new FormatException()"
            return f"Read{cs(field).removeprefix('I')}({value}!)"
        if field.get("type") == "array":
            item = f"item{nesting}"
            expression = read(field["items"], item, nesting + 1)
            if is_nullable(field["items"]): expression = f"{item} is null ? null : {expression}"
            return f"((JsonArray){value}!).Select({item} => {expression}).ToArray()"
        return f"{value}!.GetValue<{cs(field)}>()"

    nodes = []
    for shape in shapes.values():
        info = shape["x-dotkt-model"]
        name = info["name"]
        node = info["domain"] == "birCore"
        fields = [(key, field) for key, field in shape["properties"].items() if key != "k" or not node]
        tag = shape["properties"]["k"]["const"] if node else None
        if node: nodes.append((tag, name))
        lines += [f"    internal static {name} Read{name}(JsonNode source)", "    {",
                  "        var fields = source.AsObject();", "        foreach (var field in fields)",
                  "            switch (field.Key)", "            {"]
        if node:
            lines += [f'                case "k": if (field.Value?.GetValue<string>() != {json.dumps(tag)}) throw new FormatException(); break;']
        lines += [f"                case {json.dumps(key)}: break;" for key, _ in fields]
        lines += [f'                default: throw new FormatException($"Unprojected {{field.Key}} on {name} at {{source.GetPath()}}");', "            }",
                  f"        return new {name}", "        {"]
        for key, field in fields:
            prop = key[:1].upper() + key[1:]
            if refkey(field) == "birSourceTypeAlias" or refkey(field.get("items", {})) == "birSourceTypeAlias":
                # Neither the original ToDom nor this inverse boundary carries
                # aliases. Their source ownership is outside the DOM graph.
                expression = f"fields.ContainsKey({json.dumps(key)}) ? throw new FormatException() : default"
            else:
                literal = ", semanticNull: true" if refkey(field) == "literalValue" else ""
                expression = f"Field<{cs(field)}>(fields, {json.dumps(key)}, value => {read(field)}{literal})"
            lines += [f"            {prop} = {expression},"]
        lines += ["        };", "    }", ""]

    lines += ["    internal static BirGraphNode ReadNode(JsonNode source) => source[\"k\"]?.GetValue<string>() switch", "    {"]
    lines += [f"        {json.dumps(tag)} => Read{name}(source)," for tag, name in nodes]
    lines += ["        _ => throw new FormatException(),", "    };", "",
              "    internal static IBirExpression ReadBirExpression(JsonNode source) => ReadNode(source) as IBirExpression ?? throw new FormatException();",
              "    internal static IBirStatement ReadBirStatement(JsonNode source) => ReadNode(source) as IBirStatement ?? throw new FormatException();",
              "    internal static IBirAttributeValue ReadBirAttributeValue(JsonNode source) =>",
              "        source.AsObject().ContainsKey(\"k\") ? ReadBirExpression(source) :",
              "        source.AsObject().ContainsKey(\"bytes\") ? ReadBirOpaqueBytes(source) : ReadBirAttributeLiteral(source);", "",
              "    internal static IBirTypeDeclaration ReadBirTypeDeclaration(JsonNode source) => source[\"kind\"]?.GetValue<string>() switch", "    {",
              *[f'        {json.dumps(kind)} => Read{name}(source),' for kind, name in declaration_cases(definitions)],
              "        _ => throw new FormatException(),", "    };", "",
              "    private static OptionalField<T> Field<T>(JsonObject source, string name, Func<JsonNode?, T> read, bool semanticNull = false)", "    {",
              "        if (!source.TryGetPropertyValue(name, out var value)) return default;",
              "        return value is null && !semanticNull ? OptionalField<T>.Null : OptionalField<T>.Of(read(value));",
              "    }", "}", ""]
    return {root / "toolchain/bir2cir/BirGraph.Dom.Generated.cs": "\n".join(lines)}
