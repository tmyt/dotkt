"""Generate a direct typed CIR MessagePack codec from the logical IR schema."""
import json


def generate(definitions, model_type, non_null_field, allows_null):
    types = {item["$ref"].split("/")[-1] for item in definitions["type"]["oneOf"]}
    attributes = {item["$ref"].split("/")[-1] for item in definitions["cirAttributeArgument"]["oneOf"]}
    pending = []
    registered = {}
    lines = ["// <auto-generated />", "// Source: docs/bir-cir.schema.json; run scripts/generate-ir-model.py.",
             "#nullable enable", "using System;", "using System.Buffers;", "using System.Collections.Generic;",
             "using DotKt.Bir;", "using MessagePack;", "namespace DotKt.Cir;", "",
             "public static class CirMessagePack", "{",
             "    public static CirFileDeclaration Read(ref MessagePackReader reader) => Read_cirFile(ref reader);",
             "    public static void Write(ref MessagePackWriter writer, CirFileDeclaration value) => Write_cirFile(ref writer, value, 0);", ""]

    def shape_type(shape):
        shape = non_null_field(shape)
        if "$ref" in shape:
            return definition_type(shape["$ref"].split("/")[-1])
        return model_type(shape, definitions, "csharp")

    def definition_type(key):
        if key == "type":
            return "TypeNode"
        if key == "memberRef":
            return "MemberRefNode"
        if key in types or key == "sourceClassifier":
            return "TypeNode." + definitions[key]["x-dotkt-model"]["name"]
        if key in attributes:
            return "AttributeArgument." + definitions[key]["x-dotkt-model"]["name"]
        return model_type({"$ref": "#/$defs/" + key}, definitions, "csharp")

    def register(shape):
        shape = non_null_field(shape)
        if "$ref" in shape:
            key = shape["$ref"].split("/")[-1]
            token = "ref:" + key
            name = key
            target = definitions[key]
        else:
            token = json.dumps(shape, sort_keys=True)
            name = "value" + str(len(registered))
            target = shape
            key = None
        if token not in registered:
            registered[token] = name
            pending.append((name, key, target))
        return registered[token]

    def read(shape):
        return f"Read_{register(shape)}(ref reader)"

    def write(shape, value, indent="        ", depth="depth + 1"):
        key = non_null_field(shape).get("$ref", "").split("/")[-1]
        if key in types:
            value = f"({value} as {definition_type(key)} ?? throw new FormatException())"
        return f"{indent}Write_{register(shape)}(ref writer, {value}, {depth});"

    def prop(key, field):
        return field.get("x-dotkt-csharp-name", key[0].upper() + key[1:])

    def constraints(shape, value, indent):
        result = []
        if "enum" in shape and shape.get("x-dotkt-model", {}).get("name") != "CirTypeKind":
            choices = " or ".join(json.dumps(item) for item in shape["enum"])
            result.append(f"{indent}if ({value} is not ({choices})) throw new FormatException();")
        for key, op in [("minimum", "<"), ("maximum", ">")]:
            if key in shape:
                result.append(f"{indent}if ({value} {op} {shape[key]}) throw new FormatException();")
        if "minLength" in shape:
            result.append(f"{indent}if ({value}.Length < {shape['minLength']}) throw new FormatException();")
        return result

    def record(name, key, shape, value_type):
        model = shape.get("x-dotkt-model", {})
        optional_fields = model.get("domain") in {"cirDeclarations", "cirExecutable", "cirExecutableValues"}
        discriminator = "t" if key in types else "a" if key in attributes else "k" if model.get("domain") == "cirExecutable" else None
        properties = shape["properties"]
        required = shape.get("required", [])
        if len(properties) > 64:
            raise ValueError(f"{key}: expand presence mask before extending the schema")
        fields = [(k, f) for k, f in properties.items() if k != discriminator]
        lines.extend([f"    private static {value_type} Read_{name}(ref MessagePackReader reader)", "    {",
                      "        var count = ReadMap(ref reader);", "        ulong seen = 0;"])
        for k, field in fields:
            field_type = shape_type(field)
            if k not in required:
                field_type = f"OptionalField<{field_type}>" if optional_fields else field_type + "?"
            lines.append(f"        {field_type} field_{k} = default!;")
        lines.extend(["        for (var i = 0; i < count; i++)", "        {", "            switch (IrMessagePack.ReadString(ref reader))", "            {"])
        mask = 0
        for index, (k, field) in enumerate(properties.items()):
            bit = 1 << index
            if k in required:
                mask |= bit
            lines.extend([f"                case {json.dumps(k)}:", f"                    Seen(ref seen, {bit}UL);"])
            if k == discriminator:
                lines.append(f"                    if (IrMessagePack.ReadString(ref reader) != {json.dumps(field['const'])}) throw new FormatException();")
            else:
                value = read(field)
                if k not in required and optional_fields:
                    field_type = shape_type(field)
                    value = f"OptionalField<{field_type}>.Of({value})"
                    if allows_null(field, definitions):
                        value = f"reader.TryReadNil() ? OptionalField<{field_type}>.Null : {value}"
                lines.append(f"                    field_{k} = {value};")
            lines.append("                    break;")
        lines.extend(["                default: throw new FormatException();", "            }", "        }",
                      f"        if ((seen & {mask}UL) != {mask}UL) throw new FormatException();", "        reader.Depth--;"])
        if optional_fields:
            expression = f"new {value_type} {{ " + ", ".join(f"{prop(k, f)} = field_{k}" for k, f in fields) + " }"
        elif "csharpReadFactory" in model:
            expression = "TypeNode." + model["csharpReadFactory"].format_map({k: "field_" + k for k, _ in fields})
        else:
            init = model.get("csharpInit", [])
            order = model.get("csharpParameters", [k for k, _ in fields if k in required and k not in init] +
                              [k for k, _ in fields if k not in required and k not in init])
            expression = f"new {value_type}(" + ", ".join("field_" + k for k in order) + ")"
            if init:
                expression += " { " + ", ".join(f"{prop(k, properties[k])} = field_{k}" for k in init) + " }"
        lines.append(f"        var value = {expression};")
        if key == "memberRef":
            lines.append("        value.Validate();")
        lines.extend(["        return value;", "    }", "",
                      f"    private static void Write_{name}(ref MessagePackWriter writer, {value_type} node, int depth)", "    {",
                      "        CheckDepth(depth);"])
        if "csharpWriteValidation" in model:
            lines.append("        TypeNode." + model["csharpWriteValidation"] + ";")
        if key == "memberRef":
            lines.append("        node.Validate();")
        values = {}
        for k, field in fields:
            values[k] = field.get("x-dotkt-csharp-wire-value", f"node.{prop(k, field)}")
        count = str(len(required))
        for k, field in fields:
            if k not in required:
                value = values[k]
                if optional_fields:
                    count += f" + ({value}.IsPresent ? 1 : 0)"
                elif field.get("x-dotkt-omit-empty"):
                    count += f" + (({value}) is {{ Length: > 0 }} ? 1 : 0)"
                else:
                    count += f" + (({value}) is null ? 0 : 1)"
        lines.append(f"        writer.WriteMapHeader({count});")
        for k, field in properties.items():
            optional = k not in required
            indent = "            " if optional else "        "
            value = values.get(k)
            if optional:
                pattern = "{ Length: > 0 }" if field.get("x-dotkt-omit-empty") else "{ }"
                condition = f"{value}.IsPresent" if optional_fields else f"({value}) is {pattern} child_{k}"
                lines.extend([f"        if ({condition})", "        {"])
            lines.append(f"{indent}writer.Write({json.dumps(k)});")
            if k == discriminator:
                lines.append(f"{indent}writer.Write({json.dumps(field['const'])});")
            elif optional and optional_fields:
                if allows_null(field, definitions):
                    lines.extend([f"{indent}if ({value}.IsNull) writer.WriteNil();", f"{indent}else", f"{indent}{{",
                                  write(field, value + ".Value", indent + "    "), f"{indent}}}"])
                else:
                    lines.append(write(field, value + ".Value", indent))
            else:
                lines.append(write(field, f"child_{k}" if optional else value, indent))
            if optional:
                lines.append("        }")
        lines.extend(["    }", ""])

    register({"$ref": "#/$defs/cirFile"})
    while pending:
        name, key, shape = pending.pop(0)
        value_type = definition_type(key) if key else shape_type(shape)
        if "properties" in shape:
            record(name, key, shape, value_type)
            continue
        if "oneOf" in shape and not allows_null(shape, definitions):
            variants = [item["$ref"].split("/")[-1] for item in shape["oneOf"]]
            tag = "t" if key == "type" else "a" if key in {"cirAttributeArgument", "cirScalarValue"} else "k"
            lines.extend([f"    private static {value_type} Read_{name}(ref MessagePackReader reader) =>",
                          f"        Discriminator(reader, {json.dumps(tag)}) switch", "        {"])
            for variant in variants:
                target = register({"$ref": "#/$defs/" + variant})
                value = definitions[variant]["properties"][tag]["const"]
                lines.append(f"            {json.dumps(value)} => Read_{target}(ref reader),")
            lines.extend(["            _ => throw new FormatException(),", "        };", "",
                          f"    private static void Write_{name}(ref MessagePackWriter writer, {value_type} node, int depth)",
                          "    {", "        switch (node)", "        {"])
            for variant in variants:
                target = register({"$ref": "#/$defs/" + variant})
                lines.append(f"            case {definition_type(variant)} value: Write_{target}(ref writer, value, depth); break;")
            lines.extend(["            default: throw new FormatException();", "        }", "    }", ""])
            continue
        if shape.get("x-dotkt-model", {}).get("name") == "CirTypeKind":
            pairs = [(item, item[0].upper() + item[1:]) for item in shape["enum"]]
            expression = "IrMessagePack.ReadString(ref reader) switch { " + ", ".join(
                f"{json.dumps(wire)} => CirTypeKind.{member}" for wire, member in pairs) + ", _ => throw new FormatException() }"
            body = ["writer.Write(node switch { " + ", ".join(f"CirTypeKind.{member} => {json.dumps(wire)}" for wire, member in pairs) +
                    ", _ => throw new FormatException() });"]
        elif "$ref" in non_null_field(shape):
            expression = read(non_null_field(shape))
            body = [write(non_null_field(shape), "node", "", "depth")]
        elif shape.get("type") == "array" or shape.get("type") == ["array", "null"]:
            item = shape["items"]
            target = register(item)
            expression = f"ReadArray<{shape_type(item)}>(ref reader, Read_{target})"
            body = ["CheckDepth(depth);", "writer.WriteArrayHeader(node.Length);", "foreach (var child in node)", "{",
                    write(item, "child", "    "), "}"]
        elif isinstance(shape.get("additionalProperties"), dict):
            target = register(shape["additionalProperties"])
            expression = f"ReadDictionary<{shape_type(shape['additionalProperties'])}>(ref reader, Read_{target})"
            body = ["CheckDepth(depth);", "writer.WriteMapHeader(node.Count);", "foreach (var entry in node)", "{",
                    "    IrMessagePack.WriteString(ref writer, entry.Key);", write(shape["additionalProperties"], "entry.Value", "    "), "}"]
        elif value_type == "byte[]" and shape.get("type") == "string":
            expression = "reader.ReadBytes()?.ToArray() ?? throw new FormatException()"
            body = ["writer.Write(node);"]
        else:
            method = {"string": "IrMessagePack.ReadString(ref reader)", "bool": "reader.ReadBoolean()",
                      "sbyte": "reader.ReadSByte()", "byte": "reader.ReadByte()", "short": "reader.ReadInt16()",
                      "ushort": "reader.ReadUInt16()", "int": "reader.ReadInt32()", "uint": "reader.ReadUInt32()",
                      "long": "reader.ReadInt64()", "ulong": "reader.ReadUInt64()"}
            expression = method[value_type]
            body = ["IrMessagePack.WriteString(ref writer, node);" if value_type == "string" else "writer.Write(node);"]
        lines.extend([f"    private static {value_type} Read_{name}(ref MessagePackReader reader)", "    {", f"        var value = {expression};"])
        lines.extend(constraints(shape, "value", "        "))
        if "const" in shape:
            lines.append(f"        if (value != {json.dumps(shape['const'])}) throw new FormatException();")
        lines.extend(["        return value;", "    }", "",
                      f"    private static void Write_{name}(ref MessagePackWriter writer, {value_type} node, int depth)", "    {"])
        lines.extend(constraints(shape, "node", "        "))
        if "const" in shape:
            constant = json.dumps(shape["const"])
            lines.append(f"        if (node != {constant}) throw new FormatException();")
        lines.extend("        " + line for line in body)
        lines.extend(["    }", ""])
    lines.append('''    private delegate T Reader<T>(ref MessagePackReader reader);
    private static T[] ReadArray<T>(ref MessagePackReader reader, Reader<T> read)
    {
        Enter(ref reader);
        var count = reader.ReadArrayHeader();
        if (count > reader.Sequence.Length - reader.Consumed) throw new FormatException();
        var values = new T[count];
        for (var i = 0; i < count; i++) values[i] = read(ref reader);
        reader.Depth--;
        return values;
    }
    private static Dictionary<string, T> ReadDictionary<T>(ref MessagePackReader reader, Reader<T> read)
    {
        var count = ReadMap(ref reader);
        var values = new Dictionary<string, T>();
        for (var i = 0; i < count; i++) values.Add(IrMessagePack.ReadString(ref reader), read(ref reader));
        reader.Depth--;
        return values;
    }
    private static int ReadMap(ref MessagePackReader reader)
    {
        Enter(ref reader);
        var count = reader.ReadMapHeader();
        if (count > (reader.Sequence.Length - reader.Consumed) / 2) throw new FormatException();
        return count;
    }
    private static void Enter(ref MessagePackReader reader)
    {
        CheckDepth(reader.Depth);
        reader.Depth++;
    }
    private static void CheckDepth(int depth)
    {
        if (depth >= BirJson.MaxDepth) throw new FormatException();
    }
    private static void Seen(ref ulong seen, ulong bit)
    {
        if ((seen & bit) != 0) throw new FormatException();
        seen |= bit;
    }
    private static string Discriminator(MessagePackReader reader, string key)
    {
        var count = ReadMap(ref reader);
        for (var i = 0; i < count; i++)
        {
            if (IrMessagePack.ReadString(ref reader) == key) return IrMessagePack.ReadString(ref reader);
            reader.Skip();
        }
        throw new FormatException();
    }
}
''')
    return "\n".join(lines)
