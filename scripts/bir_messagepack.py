"""Direct typed BIR transport over the existing owning phase composition."""
import json
from bir_lowering_models import base, compose_shapes, csharp_type, is_nullable, refkey


def outputs(root, definitions):
    shapes = compose_shapes(definitions)
    cs = lambda field: csharp_type(field, shapes)
    lines = ["// <auto-generated />", "// Source: docs/bir-cir.schema.json; run scripts/generate-ir-model.py.",
             "#nullable enable", "using System.Buffers;", "using DotKt.Cir;", "using MessagePack;",
             "namespace DotKt.Bir.Lowering;", "", "internal static class BirGraphMessagePack", "{",
             "    internal static BirFileDeclaration Read(ref MessagePackReader reader) => ReadBirFileDeclaration(ref reader);",
             "    internal static void Write(ref MessagePackWriter writer, BirFileDeclaration value) => WriteBirFileDeclaration(ref writer, value, 0);", ""]

    def read(field):
        field = base(field)
        if codec := field.get("x-dotkt-csharp-codec"):
            return f"{codec}.ReadFrozenText(IrMessagePack.ReadString(ref reader))"
        if cs(field) == "byte[]":
            return "reader.ReadBytes()?.ToArray() ?? throw new FormatException()"
        if field.get("x-dotkt-kotlin-json-type"):
            return "TypeNode.Parse(IrMessagePack.ReadString(ref reader))"
        key = refkey(field)
        if key:
            if key == "type": return "CirMessagePack.ReadType(ref reader)"
            if key == "literalValue": return "BirLiteralMessagePack.Read(ref reader)"
            if key == "birSourceTypeAlias": return "SourceMetadataMessagePack.Read(ref reader)"
            return f"Read{cs(field).removeprefix('I')}(ref reader)"
        if field.get("type") == "array":
            item = field["items"]
            body = read(item)
            if is_nullable(item): body = f"reader.TryReadNil() ? null : {body}"
            item_type = cs(item) + ("?" if is_nullable(item) else "")
            return f"ReadArray<{item_type}>(ref reader, (ref MessagePackReader reader) => {body})"
        return {"string": "IrMessagePack.ReadString(ref reader)", "int": "reader.ReadInt32()",
                "bool": "reader.ReadBoolean()"}[cs(field)]

    def write(field, value, depth="depth + 1", indent="            ", nesting=0):
        field = base(field)
        if codec := field.get("x-dotkt-csharp-codec"):
            return [indent + f"IrMessagePack.WriteString(ref writer, {value}.FrozenText);"]
        if cs(field) == "byte[]": return [indent + f"writer.Write({value});"]
        if field.get("x-dotkt-kotlin-json-type"):
            return [indent + f"IrMessagePack.WriteString(ref writer, TypeNode.ToJson({value}));"]
        key = refkey(field)
        if key:
            if key == "type": body = f"CirMessagePack.WriteType(ref writer, {value}, {depth});"
            elif key == "literalValue": body = f"BirLiteralMessagePack.Write(ref writer, {value}, {depth});"
            elif key == "birSourceTypeAlias": body = f"SourceMetadataMessagePack.Write(ref writer, {value}, {depth});"
            else: body = f"Write{cs(field).removeprefix('I')}(ref writer, {value}, {depth});"
            return [indent + body]
        if field.get("type") == "array":
            item = f"item{nesting}"
            result = [indent + f"CheckDepth({depth});", indent + f"writer.WriteArrayHeader({value}.Length);",
                      indent + f"foreach (var {item} in {value})", indent + "{"]
            if is_nullable(field["items"]):
                result += [indent + f"    if ({item} is null) writer.WriteNil();", indent + "    else", indent + "    {"]
                result += write(field["items"], item, f"{depth} + 1", indent + "        ", nesting + 1) + [indent + "    }"]
            else:
                result += write(field["items"], item, f"{depth} + 1", indent + "    ", nesting + 1)
            return result + [indent + "}"]
        return [indent + (f"IrMessagePack.WriteString(ref writer, {value});" if cs(field) == "string" else f"writer.Write({value});")]

    nodes = []
    for shape in shapes.values():
        info = shape["x-dotkt-model"]
        name = info["name"]
        node = info["domain"] == "birCore"
        fields = [(key, field) for key, field in shape["properties"].items() if key != "k" or not node]
        if len(fields) + node > 64:
            raise ValueError(f"Expand duplicate-field tracking before extending {name}")
        tag = shape["properties"]["k"]["const"] if node else None
        if node: nodes.append((tag, name))
        lines += [f"    internal static {name} Read{name}(ref MessagePackReader reader)", "    {",
                  "        var count = ReadMap(ref reader);", "        ulong seen = 0;"]
        lines += [f"        OptionalField<{cs(field)}> field{index} = default;" for index, (_, field) in enumerate(fields)]
        lines += ["        for (var index = 0; index < count; index++)", "        {",
                  "            switch (IrMessagePack.ReadString(ref reader))", "            {"]
        if node:
            lines += [f'                case "k": Seen(ref seen, 1UL << {len(fields)}); if (IrMessagePack.ReadString(ref reader) != {json.dumps(tag)}) throw new FormatException(); break;']
        for index, (key, field) in enumerate(fields):
            value = f"OptionalField<{cs(field)}>.Of({read(field)})"
            if refkey(field) != "literalValue": value = f"reader.TryReadNil() ? OptionalField<{cs(field)}>.Null : {value}"
            lines += [f"                case {json.dumps(key)}:", f"                    Seen(ref seen, 1UL << {index});",
                      f"                    field{index} = {value};", "                    break;"]
        lines += ["                default: throw new FormatException();", "            }", "        }", "        reader.Depth--;",
                  f"        return new {name}", "        {"]
        lines += [f"            {key[:1].upper() + key[1:]} = field{index}," for index, (key, _) in enumerate(fields)]
        lines += ["        };", "    }", "",
                  f"    internal static void Write{name}(ref MessagePackWriter writer, {name} value, int depth)", "    {", "        CheckDepth(depth);"]
        size = ("1" if node else "0") + "".join(f" + (value.{key[:1].upper() + key[1:]}.IsPresent ? 1 : 0)" for key, _ in fields)
        lines += [f"        writer.WriteMapHeader({size});"]
        if node: lines += ['        writer.Write("k");', f"        writer.Write({json.dumps(tag)});"]
        for key, field in fields:
            prop = "value." + key[:1].upper() + key[1:]
            lines += [f"        if ({prop}.IsPresent)", "        {", f"            writer.Write({json.dumps(key)});",
                      f"            if ({prop}.IsNull) writer.WriteNil();", "            else", "            {"]
            lines += write(field, prop + ".Value", indent="                ")
            lines += ["            }", "        }"]
        lines += ["    }", ""]
    lines += ["    internal static BirGraphNode ReadNode(ref MessagePackReader reader) => Discriminator(reader, \"k\") switch", "    {"]
    lines += [f"        {json.dumps(tag)} => Read{name}(ref reader)," for tag, name in nodes]
    lines += ["        _ => throw new FormatException(),", "    };", "",
              "    internal static void WriteNode(ref MessagePackWriter writer, BirGraphNode value, int depth)", "    {", "        switch (value)", "        {"]
    lines += [f"            case {name} node: Write{name}(ref writer, node, depth); break;" for _, name in nodes]
    lines += ["            default: throw new FormatException();", "        }", "    }", ""]
    for role in ("Expression", "Statement"):
        lines += [f"    internal static IBir{role} ReadBir{role}(ref MessagePackReader reader) => ReadNode(ref reader) as IBir{role} ?? throw new FormatException();",
                  f"    internal static void WriteBir{role}(ref MessagePackWriter writer, IBir{role} value, int depth) => WriteNode(ref writer, (BirGraphNode)value, depth);", ""]
    lines += ["    internal static IBirAttributeValue ReadBirAttributeValue(ref MessagePackReader reader) =>",
              '        HasProperty(reader, "bytes") ? ReadBirOpaqueBytes(ref reader) : ReadBirExpression(ref reader);',
              "    internal static void WriteBirAttributeValue(ref MessagePackWriter writer, IBirAttributeValue value, int depth)", "    {",
              "        if (value is BirOpaqueBytes bytes) WriteBirOpaqueBytes(ref writer, bytes, depth);",
              "        else WriteBirExpression(ref writer, (IBirExpression)value, depth);", "    }", "",
              "    internal static IBirTypeDeclaration ReadBirTypeDeclaration(ref MessagePackReader reader) => Discriminator(reader, \"kind\") switch", "    {",
              '        "class" => ReadBirClassDefinition(ref reader),', '        "interface" => ReadBirInterfaceDefinition(ref reader),',
              '        "enum" => ReadBirEnumDefinition(ref reader),', "        _ => throw new FormatException(),", "    };",
              "    internal static void WriteBirTypeDeclaration(ref MessagePackWriter writer, IBirTypeDeclaration value, int depth)", "    {", "        switch (value)", "        {",
              "            case BirClassDefinition node: WriteBirClassDefinition(ref writer, node, depth); break;",
              "            case BirInterfaceDefinition node: WriteBirInterfaceDefinition(ref writer, node, depth); break;",
              "            case BirEnumDefinition node: WriteBirEnumDefinition(ref writer, node, depth); break;",
              "            default: throw new FormatException();", "        }", "    }", "",
              "    private delegate T Reader<T>(ref MessagePackReader reader);",
              "    private static T[] ReadArray<T>(ref MessagePackReader reader, Reader<T> read)", "    {",
              "        Enter(ref reader);", "        var count = reader.ReadArrayHeader();",
              "        if (count > reader.Sequence.Length - reader.Consumed) throw new FormatException();",
              "        var result = new T[count];", "        for (var index = 0; index < count; index++) result[index] = read(ref reader);",
              "        reader.Depth--;", "        return result;", "    }",
              "    private static int ReadMap(ref MessagePackReader reader)", "    {", "        Enter(ref reader);",
              "        var count = reader.ReadMapHeader();", "        if (count > (reader.Sequence.Length - reader.Consumed) / 2) throw new FormatException();",
              "        return count;", "    }",
              "    private static void Enter(ref MessagePackReader reader) { CheckDepth(reader.Depth); reader.Depth++; }",
              "    private static void CheckDepth(int depth) { if (depth >= BirJson.MaxDepth) throw new FormatException(); }",
              "    private static void Seen(ref ulong seen, ulong bit) { if ((seen & bit) != 0) throw new FormatException(); seen |= bit; }",
              "    private static string Discriminator(MessagePackReader reader, string key)", "    {", "        var count = ReadMap(ref reader);",
              "        for (var index = 0; index < count; index++)", "        {",
              "            if (IrMessagePack.ReadString(ref reader) == key) return IrMessagePack.ReadString(ref reader);", "            reader.Skip();",
              "        }", "        throw new FormatException();", "    }",
              "    private static bool HasProperty(MessagePackReader reader, string key)", "    {", "        var count = ReadMap(ref reader);",
              "        for (var index = 0; index < count; index++)", "        {",
              "            if (IrMessagePack.ReadString(ref reader) == key) return true;", "            reader.Skip();",
              "        }", "        return false;", "    }", "}", ""]
    return {root / "toolchain/bir2cir/BirGraph.MessagePack.Generated.cs": "\n".join(lines)}
