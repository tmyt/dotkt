"""Final owning lowering graph -> physical CIR, from the maintained phase profiles.

The generator consumes the same source/physical correspondence as compose_shapes.
It emits typed property access, not a dynamic field bag or a serialization bridge.
Every remaining lowering-only fact must be explicitly consumed or absent.
"""
import json
from bir_lowering_models import PHYSICAL_ALIASES, PHYSICAL_DECLARATIONS, compose_shapes, refkey


def outputs(root, definitions, model_type, non_null_field, allows_null):
    shapes = compose_shapes(definitions)
    selected = {key: shape for key, shape in definitions.items() if isinstance(shape, dict)
                and shape.get("x-dotkt-model", {}).get("domain") in
                {"cirDeclarations", "cirExecutable", "cirExecutableValues"}}
    by_tag = {shape["properties"]["k"]["const"]: key for key, shape in shapes.items()
              if shape["x-dotkt-model"].get("domain") == "birCore"}

    def source_keys(key, shape):
        if shape["x-dotkt-model"].get("domain") == "cirExecutable":
            return [by_tag[shape["properties"]["k"]["const"]]]
        return PHYSICAL_DECLARATIONS.get(key, [PHYSICAL_ALIASES.get(key, key)])

    def target_type(field):
        return model_type(field, definitions, "csharp")

    def convert(field, value, depth=0):
        field = non_null_field(field)
        key = refkey(field)
        if key:
            if key in {"type", "tFqn"}: return value
            if key == "memberRef": return f"ProjectMemberReference({value})"
            if key == "cirAttributeApplication": return f"ProjectAttribute({value})"
            if key == "cirAttributeArgument": return f"ProjectAttributeArgument({value})"
            if key in {"cirExpression", "cirExpressionNode"}: return f"ProjectExpression({value})"
            if key == "cirStatementNode": return f"ProjectStatement({value})"
            if key in {"cirStatementList", "cirExpressionList"}:
                item = f"item{depth}"
                method = "ProjectStatement" if key == "cirStatementList" else "ProjectExpression"
                return f"{value}.Select({item} => {method}({item})).ToArray()"
            return f"Project{target_type(field)}({value})"
        if field.get("type") == "array":
            item = f"item{depth}"
            expression = convert(field["items"], item, depth + 1)
            # Metadata admission operates on the already-selected type declaration set.
            if refkey(field["items"]) == "cirAttributeApplication":
                return f"{value}.Where(AdmitAttribute).Select({item} => {expression}).ToArray()"
            return f"{value}.Select({item} => {expression}).ToArray()"
        if field.get("type") == "object" and "additionalProperties" in field:
            # The one typed role table is not an IR field bag; its values already
            # own the selected exact member identity.
            if refkey(field["additionalProperties"]) != "memberRef":
                raise ValueError("Unaccounted physical dictionary projection")
            return f"{value}.Members.ToDictionary(pair => pair.Key, pair => pair.Value, StringComparer.Ordinal)"
        return value

    lines = ["// <auto-generated />", "// Source: docs/bir-cir.schema.json; run scripts/generate-ir-model.py.",
             "#nullable enable", "using DotKt.Bir;", "using DotKt.Bir.Lowering;", "using DotKt.Cir;", "",
             "sealed partial class TypedCirProjection", "{"]
    nodes = [shape for shape in selected.values()
             if shape["x-dotkt-model"].get("domain") == "cirExecutable"]
    lines += ["    internal CirNode ProjectNode(BirGraphValue value) => value switch", "    {"]
    for shape in nodes:
        source = shapes[source_keys("", shape)[0]]["x-dotkt-model"]["name"]
        target = shape["x-dotkt-model"]["name"]
        lines += [f"        {source} node => Project{target}(node),"]
    lines += ['        _ => throw new InvalidOperationException("Unconsumed executable lowering node"),', "    };", "",
              "    ICirExpression ProjectExpression(IBirExpression value) => ProjectNode((BirGraphValue)value) as ICirExpression ?? throw new FormatException();",
              "    ICirStatement ProjectStatement(IBirStatement value) => ProjectNode((BirGraphValue)value) as ICirStatement ?? throw new FormatException();", ""]

    for key, shape in selected.items():
        info = shape["x-dotkt-model"]
        target = info["name"]
        if "enum" in shape:
            lines += [f"    static {target} Project{target}(string value) => value switch", "    {"]
            lines += [f"        {json.dumps(item)} => {target}.{item[0].upper() + item[1:]}," for item in shape["enum"]]
            lines += ["        _ => throw new FormatException(),", "    };", ""]
            continue
        sources = source_keys(key, shape)
        if len(sources) > 1:
            lines += [f"    internal {target} Project{target}(IBirTypeDeclaration value) => value switch", "    {"]
            for source in sources:
                source_name = shapes[source]["x-dotkt-model"]["name"]
                lines += [f"        {source_name} node => Project{target}(node),"]
            lines += ["        _ => throw new FormatException(),", "    };", ""]
        for source_key in sources:
            source = shapes[source_key]
            source_name = source["x-dotkt-model"]["name"]
            allowed = set(shape["properties"]) | set(info.get("sourceConsumed", []))
            extras = source["properties"].keys() - allowed
            conditions = [f"value.{name[0].upper() + name[1:]}.IsPresent" for name in sorted(extras) if name != "k"]
            lines += [f"    internal {target} Project{target}({source_name} value)", "    {"]
            if conditions:
                lines += ["        if (" + " || ".join(conditions) + ")",
                          f'            throw new InvalidOperationException("Unconsumed lowering fact on {source_name}");']
            if "sty" in info.get("sourceConsumed", []):
                for result in ("ret", "dynRet"):
                    if result in source["properties"]:
                        member = result[0].upper() + result[1:]
                        lines += [f"        CheckSourceStamp(value.Sty, value.{member});"]
            lines += [f"        return new {target}", "        {"]
            for name, field in shape["properties"].items():
                if name == "k" and info.get("domain") == "cirExecutable": continue
                member = name[0].upper() + name[1:]
                source_field = "value." + member
                if name not in source["properties"]:
                    raise ValueError(f"Missing typed physical field {source_key}.{name}")
                if target == "CirConstant" and name == "value":
                    expression = "ProjectExecutableLiteral(Require(value.Value), Require(value.Type))"
                elif target == "CirField" and name == "constant":
                    expression = "value.Constant.IsPresent ? OptionalField<AttributeArgument>.Of(AttributeProjection.Literal(value.Constant.IsNull ? new BirLiteral.NullLiteral() : value.Constant.Value, Require(value.Type))) : default"
                elif name in shape.get("required", []):
                    expression = convert(field, f"Require({source_field})")
                    if name in info.get("sourceDefaults", {}):
                        default = info["sourceDefaults"][name]
                        literal = "[]" if default == [] else json.dumps(default)
                        expression = f"{source_field}.IsPresent ? {expression} : {literal}"
                else:
                    expression = convert(field, "item")
                    null = "true" if allows_null(field, definitions) else "false"
                    expression = f"ProjectOptional({source_field}, item => {expression}, allowNull: {null})"
                lines += [f"            {member} = {expression},"]
            lines += ["        };", "    }", ""]
    return {root / "toolchain/bir2cir/TypedCirProjection.Generated.cs": "\n".join([*lines, "}", ""])}
